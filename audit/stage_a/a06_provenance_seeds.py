"""Stage A: provenance and seed checks without re-running any simulation.

For each stochastic dataset, back out the per-period noise implied by the
agent update rule in the committed code (one-step formula evaluation on the
recorded prices), then compare it with the normal draws that the seed policy
in the committed experiment script would produce (np.random.default_rng(seed)).
Exact agreement (to floating-point precision) means the committed CSV was
generated by the committed code with the stated seeds.
Deterministic datasets are checked step by step against the committed rules.

Run from the repository root:  python audit/stage_a/a06_provenance_seeds.py
"""
import sys
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from simulator.market import BertrandMarket, MarketConfig  # noqa: E402
from simulator.reactive_agents import ReactiveCompetitiveAgent  # noqa: E402
from simulator.agents import CompetitiveAgent  # noqa: E402

mkt = BertrandMarket(MarketConfig())
BASE = 1.472927


@lru_cache(maxsize=None)
def br_reactive(firm_id, cost, rival_price):
    a = ReactiveCompetitiveAgent(cost=cost, firm_id=firm_id)
    return a.competitive_best_response(rival_price, mkt, Q=1.0)


def implied_noise_reactive(p_own, p_riv, firm_id, cost, speed=0.4):
    """eps_{t+1} = p_{t+1} - cur_t - speed*(BR(p_riv_t) - cur_t); cur_0 = BR(p_riv_0)."""
    eps = []
    cur = br_reactive(firm_id, cost, float(p_riv[0]))  # internal state set on first call
    for t in range(len(p_own) - 1):
        target = br_reactive(firm_id, cost, float(p_riv[t]))
        eps.append(p_own[t + 1] - (cur + speed * (target - cur)))
        cur = p_own[t + 1]
    return np.array(eps)


def check_reactive(name, df, seed_fn, costs_fn, n_runs=None):
    df = df.sort_values(["run_id", "period"])
    rows = []
    for k, (rid, g) in enumerate(df.groupby("run_id")):
        if n_runs is not None and k >= n_runs:
            break
        p1, p2 = g.price_1.to_numpy(), g.price_2.to_numpy()
        c1, c2 = costs_fn(g)
        e1 = implied_noise_reactive(p1, p2, 1, c1)
        e2 = implied_noise_reactive(p2, p1, 2, c2)
        s1, s2 = seed_fn(rid)
        r1 = np.random.default_rng(s1).normal(0.0, 0.01, len(e1))
        r2 = np.random.default_rng(s2).normal(0.0, 0.01, len(e2))
        rows.append({"run_id": rid, "seed1": s1, "seed2": s2,
                     "max|e1-draw|": np.abs(e1 - r1).max(), "max|e2-draw|": np.abs(e2 - r2).max(),
                     "sd_e1": e1.std(ddof=1), "sd_e2": e2.std(ddof=1)})
    r = pd.DataFrame(rows)
    ok = (r[["max|e1-draw|", "max|e2-draw|"]].max(axis=1) < 1e-6)
    print(f"{name}: runs checked={len(r)}; runs whose implied noise equals the seeded draws (<1e-6): {int(ok.sum())}; "
          f"worst max diff={r[['max|e1-draw|','max|e2-draw|']].to_numpy().max():.2e}; "
          f"implied-noise SD range=({r[['sd_e1','sd_e2']].to_numpy().min():.4f},{r[['sd_e1','sd_e2']].to_numpy().max():.4f})")
    return r


